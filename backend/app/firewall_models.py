from decimal import Decimal
from typing import Annotated, Literal

from pydantic import Field, model_validator

from app.models import StrictModel, TokenUsage

ActionType = Literal["delete", "purchase", "send_message"]
Level = Literal["allow", "remind", "confirm", "cooldown"]
ShortText = Annotated[str, Field(min_length=1, max_length=500)]
Money = Annotated[Decimal, Field(ge=0, max_digits=14, decimal_places=2)]
Currency = Annotated[str, Field(pattern=r"^[A-Z]{3}$")]


class DeleteAction(StrictModel):
    type: Literal["delete"]
    target: ShortText
    file_count: int = Field(ge=1, le=100_000_000)
    important_items: list[ShortText] = Field(default_factory=list, max_length=30)
    permanent: bool
    supports_trash: bool = False


class PurchaseAction(StrictModel):
    type: Literal["purchase"]
    item: ShortText
    amount: Money
    currency: Currency
    # Already available for spending after planned savings, in the same currency.
    remaining_budget: Money | None = None


class SendMessageAction(StrictModel):
    type: Literal["send_message"]
    recipient: ShortText
    content: Annotated[str, Field(min_length=1, max_length=8000)]
    public: bool = False


Action = Annotated[DeleteAction | PurchaseAction | SendMessageAction, Field(discriminator="type")]


class SpendingRule(StrictModel):
    threshold: Money
    currency: Currency


class PurchaseCooldownRule(SpendingRule):
    enabled: bool = False
    minutes: int = Field(ge=1, le=10080)


class Preferences(StrictModel):
    # Explicit opt-in. An unprotected action is never sent to the external model.
    protected_actions: list[ActionType] = Field(default_factory=list, max_length=3)
    spending_reminder: SpendingRule | None = None
    purchase_cooldown: PurchaseCooldownRule | None = None
    important_paths: list[ShortText] = Field(default_factory=list, max_length=30)
    personal_principles: list[ShortText] = Field(default_factory=list, max_length=10)
    savings_goals: list[ShortText] = Field(default_factory=list, max_length=10)
    expression_style: Literal["concise", "gentle", "direct"] = "gentle"


class AssessmentRequest(StrictModel):
    action: Action
    preferences: Preferences

    @model_validator(mode="after")
    def limit_context(self):
        if len(self.model_dump_json()) > 16_000:
            raise ValueError("Assessment context exceeds 16000 characters")
        return self


class ModelAssessment(StrictModel):
    # Only code can select cooldown, from a matching user rule.
    level: Literal["allow", "remind", "confirm"]
    reason: Annotated[
        str, Field(min_length=1, max_length=1500, description="Explain the assessment in English.")
    ]
    evidence_ids: list[Annotated[str, Field(min_length=1, max_length=200)]] = Field(max_length=15)


class Evidence(StrictModel):
    id: str
    source: Literal["operation", "user_rule"]
    # JSON-encoded exact input value; never generated by the model.
    value: str


class Alternative(StrictModel):
    id: str
    label: str


class AssessmentResponse(StrictModel):
    level: Level
    reason: str
    evidence: list[Evidence]
    alternatives: list[Alternative]
    cooldown_minutes: int | None = None
    source: Literal["model", "scope_check"]
    model: str | None = None
    usage: TokenUsage | None = None
